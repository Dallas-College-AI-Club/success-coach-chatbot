# Command-Line Interface
# ==========================================================
# Handles terminal arguments and decides whether the script
# should only validate the dataset or also load it into Neon.
def main() -> None:
    """Run validation or load rows into Neon."""

    parser = argparse.ArgumentParser(
        description=(
            "Validate and load catalog, supplemental program, "
            "or CV rows into the Neon knowledge_entry table."
        )
    )

    parser.add_argument(
        "json_path",
        type=Path,
        help="Path to the JSON file.",
    )

    parser.add_argument(
        "--load",
        action="store_true",
        help=(
            "Write rows to Neon after validation. "
            "Without this option, the script only validates."
        ),
    )

    parser.add_argument(
        "--supplemental-programs",
        action="store_true",
        help=(
            "Accept a program_map-only delivery. Requires --expect."
        ),
    )

    parser.add_argument(
        "--expect",
        type=int,
        default=None,
        help=(
            "Number of rows a supplemental delivery should contain, "
            "e.g. --expect 19. Stating it catches a truncated or "
            "double-written file."
        ),
    )

    parser.add_argument(
        "--batch-size",
        type=int,
        default=100,
        help=(
            "Number of rows written in each database "
            "batch. Default: 100."
        ),
    )

    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help=(
            "Optional number of rows to load for "
            "a small database test."
        ),
    )

    args = parser.parse_args()

    if (
        args.supplemental_programs
        and args.limit is not None
    ):
        parser.error(
            "--limit cannot be used with "
            "--supplemental-programs."
        )

    if args.supplemental_programs and args.expect is None:
        parser.error(
            "--supplemental-programs requires --expect N "
            "(the number of rows the file should contain)."
        )

    if args.expect is not None and not args.supplemental_programs:
        parser.error(
            "--expect only applies to --supplemental-programs."
        )

    rows = load_rows(
        args.json_path,
        allow_supplemental_programs=(
            args.supplemental_programs
        ),
        expected_supplemental_rows=args.expect,
    )

    if not args.load:
        print(
            "\nValidation only. "
            "Neon was not modified.",
            flush=True,
        )
        return

    load_into_neon(
        rows=rows,
        batch_size=args.batch_size,
        limit=args.limit,
    )

# ==========================================================
# Script Entry Point
# ==========================================================
# Runs main() only when this file is executed directly.
if __name__ == "__main__":
    main()